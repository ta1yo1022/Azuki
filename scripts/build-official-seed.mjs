import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import assert from "node:assert/strict";
import { contentHash } from "../shared/content.ts";
import { parseDeck } from "../shared/model.ts";
import { OFFICIAL_OWNER_ID } from "../worker/official.ts";

const root = new URL("../content/official/", import.meta.url);
const manifest = JSON.parse(readFileSync(new URL("manifest.json", root), "utf8"));
const audit = JSON.parse(readFileSync(new URL("source-entries.json", root), "utf8"));
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";
const hash = value => createHash("sha256").update(value).digest("hex");
const revision = manifest.version;
assert.equal(revision, 3);
assert.equal(manifest.decks.length, 5);
assert.equal(audit.length, 2500);
const owner = quote(OFFICIAL_OWNER_ID);
const sql = [
  "-- Generated by npm run content:build. Preserves shared deck IDs and saved user copies.",
  "-- Run as one D1 remote file import (atomic); do not add BEGIN/COMMIT.",
  `INSERT OR IGNORE INTO users(id) VALUES (${owner});`,
];
let total = 0;
for (const [index, entry] of manifest.decks.entries()) {
  assert.match(entry.id, /^azuki-official-[a-z]+-v1$/);
  assert(["beginner", "intermediate", "advanced"].includes(entry.level));
  const theme = entry.id.split("-")[2];
  const raw = readFileSync(new URL(entry.file, root), "utf8");
  assert.equal(hash(raw), entry.sha256, `Content checksum: ${entry.file}`);
  const deck = parseDeck(raw);
  assert.equal(deck.words.length, 500);
  assert.equal(entry.wordCount, deck.words.length);
  assert.equal(entry.exampleCount, 500);
  const bytes = Buffer.byteLength(JSON.stringify(deck));
  const id = quote(entry.id);
  const created = quote(new Date(Date.parse(manifest.source.retrievedAt) - index * 1000).toISOString());
  const updated = quote(new Date(manifest.updatedAt).toISOString());
  const guard = `id=${id} AND owner_id=${owner} AND content_source='ejdict' AND official_revision<${revision}`;
  const eligible = `EXISTS(SELECT 1 FROM decks WHERE ${guard})`;
  // Existing rows are filtered BEFORE quota triggers. A versioned update charges
  // only the increase, through the same counters and global limits as imports.
  sql.push(`INSERT INTO decks(id,owner_id,title,description,visibility,word_count,created_at,updated_at,data_bytes,content_source)
SELECT ${id},${owner},${quote(deck.title)},${quote(deck.description)},'private',500,${created},${updated},${bytes},'ejdict'
WHERE NOT EXISTS(SELECT 1 FROM decks WHERE id=${id});`);
  sql.push(`UPDATE decks SET title=${quote(deck.title)},description=${quote(deck.description)},visibility='private',word_count=500,
updated_at=${updated},data_bytes=${bytes},official_level=${quote(entry.level)} WHERE ${guard};`);
  sql.push(`DELETE FROM words WHERE deck_id=${id} AND ${eligible};`);
  sql.push(`DELETE FROM deck_textbook_tags WHERE deck_id=${id} AND ${eligible};`);
  const seen = new Set();
  const seenExamples = new Set();
  for (const [ordinal, word] of deck.words.entries()) {
    const normalized = word.word.normalize("NFKC").toLowerCase();
    assert(!seen.has(normalized), `Repeated word in ${theme}: ${word.word}`);
    seen.add(normalized);
    assert(word.example && word.example.trim().length >= 10, `Missing example: ${theme}/${word.word}`);
    assert(/[.!?]$/.test(word.example), `Incomplete example: ${theme}/${word.word}`);
    assert(!seenExamples.has(word.example), `Repeated example: ${theme}/${word.word}`);
    seenExamples.add(word.example);
    assert(word.tags.length > 0, `Missing tags: ${word.word}`);
    const evidence = audit.filter(row => row.deck === theme && row.word === word.word);
    assert.equal(evidence.length, 1, `Source evidence: ${theme}/${word.word}`);
    assert.equal(evidence[0].selectedMeaning, word.meaning);
    assert(evidence[0].entries.some(row => row.headword.split(",").some(alias => alias.trim().toLowerCase() === normalized)));
    assert(!word.meaning.startsWith("="), `Unresolved cross-reference: ${word.word}`);
    sql.push(`INSERT INTO words(id,deck_id,ordinal,word,meaning,example,tags)
SELECT ${quote(`${entry.id}-${ordinal}`)},${id},${ordinal},${quote(word.word)},${quote(word.meaning)},${quote(word.example ?? "")},${quote(JSON.stringify(word.tags))}
WHERE ${eligible};`);
  }
  for (const tag of deck.textbookTags) {
    const fields = [tag.name, tag.edition ?? "", tag.chapter ?? ""];
    const tagId = quote(`azuki-tag-${hash(JSON.stringify(fields)).slice(0, 24)}`);
    sql.push(`INSERT OR IGNORE INTO textbook_tags(id,name,edition,chapter)
SELECT ${tagId},${fields.map(quote).join(",")} WHERE ${eligible};`);
    sql.push(`INSERT OR IGNORE INTO deck_textbook_tags(deck_id,tag_id)
SELECT ${id},id FROM textbook_tags WHERE name=${quote(fields[0])} AND edition=${quote(fields[1])} AND chapter=${quote(fields[2])} AND ${eligible};`);
  }
  // A failed count violates the revision CHECK and rolls back the remote import.
  sql.push(`UPDATE decks SET content_hash=${quote(await contentHash(deck.words))},visibility='public',official_revision=(CASE WHEN
    (SELECT count(*) FROM words WHERE deck_id=${id})=500 THEN ${revision} ELSE -1 END)
WHERE ${guard};`);
  total += deck.words.length;
}
assert.equal(total, 2500);
writeFileSync(new URL("seed.sql", root), sql.join("\n") + "\n");
console.log(`Validated 5 books / ${total} entries; wrote revision ${revision} seed.sql`);
